import assert from 'node:assert/strict';
import { GameOrchestrator } from '../src/orchestrator/GameOrchestrator.js';
import { RequestSessionRepository } from '../src/persistence/RequestSessionRepository.js';
import { validateAction } from '../src/services/ActionValidator.js';
import { evidenceDetails, actionText, componentAccess } from '../../src/shared/InvestigationRules.mjs';
import { prepareAction, state } from '../src/services/InvestigationDirector.js';
const repo=new RequestSessionRepository();
let calls=0;
const engine=new GameOrchestrator({repository:repo,llmProvider:{generate(){calls++;throw Error('not needed');}}});
const s=repo.findById(engine.createBirchStationTutorial().session.id);
assert.equal(evidenceDetails(s,'evidence_007'),null,'undiscovered cards stay hidden');
s.evidence.push({id:'evidence_003',source:'针孔与医疗记录',discovered:true,secured:false,artifacts:[]});
const details=evidenceDetails(s,'evidence_003');
assert.ok(!JSON.stringify(details).includes('医疗档案室'),'unknown location is not disclosed');
assert.equal(details.rows[0].action.kind,'preserve');
assert.equal(details.rows[1].action,null);
assert.equal(componentAccess(s,'evidence_003','medical').ok,false);
assert.equal(validateAction(s,'给门锁刮痕拍照，放置比例尺并标注位置').ok,true);
assert.equal(validateAction(s,'给门锁刮痕拍照，然后标注位置').ok,true);
assert.equal(validateAction(s,'观察情况，如果有人攻击就逃跑').ok,true);
assert.equal(validateAction(s,'拍摄苏棠的画作和乘客名册').ok,false,'inaccessible materials');
for(const text of ['去办公室拍摄记录，然后找林晚录音','进入行李车并调查湿泥','给门锁拍照并给地毯湿泥取样','调查门锁并询问林晚','进入矿难转运室','说服林晚并录音保存证词','处理一下']) {
  assert.equal(validateAction(s,text).ok,false,text);
  const before=JSON.stringify({clock:s.scenarioClock,evidence:s.evidence,events:s.scheduledEvents,flags:s.scenarioFlags});
  const response=await engine.handleMessage(s.id,text);
  assert.equal(response.result.branch,'CLARIFICATION',text);
  assert.equal(JSON.stringify({clock:s.scenarioClock,evidence:s.evidence,events:s.scheduledEvents,flags:s.scenarioFlags}),before,'no gameplay mutation');
}
assert.equal(calls,0);
const invalid=await engine.handleMessage(s.id,'随意文字',{action:{kind:'preserve',evidenceId:'unknown',component:'record'}});
assert.equal(invalid.result.branch,'CLARIFICATION');
const action=details.rows[0].action;
assert.equal(validateAction(s,actionText(s,action)).ok,true);
prepareAction(s,actionText(s,action));
assert.equal(evidenceDetails(s,'evidence_003').rows[0].done,true);
s.playerLocationId='loc_005';
assert.equal(validateAction(s,'拍摄苏棠的画作和乘客名册').ok,true,'one comparison objective');
s.playerLocationId='loc_001';
state(s).visited=['loc_001','loc_002'];
assert.equal(validateAction(s,'进入行李车').cost,0);
s.combat={active:true};
assert.equal(validateAction(s,'进入行李车').cost,1,'combat cannot become free movement');
assert.equal(validateAction(s,'包扎伤口').ok,false);
console.log('Shared evidence details, structured actions and free preflight checks passed');
